// Validates the factory preset JSON files in presets/ (schema v1, docs/PROTOCOL.md) and emits
// firmware/app/factory_presets.h so the device can restore them without the companion.
//   node presets/gen_presets_h.mjs            (writes the header; exits 1 on any validation error)
//   node presets/gen_presets_h.mjs --check    (validate only)
// Factory files are validated strictly: anything an importer would have to clamp is an error here.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../', import.meta.url);
const FX_IDS = ['none', 'filter', 'chorus', 'delay', 'reverb', 'saturation', 'flanger', 'bitcrusher', 'tremolo', 'compressor', 'tape_wobble'];
// Order of presets in the firmware table (index = factory preset number).
const FILES = ['dub_station.json', 'boom_bap.json', 'house.json', 'lofi_tape.json', 'ambient.json', 'clean.json'];

const fxTable = JSON.parse(readFileSync(new URL('companion/data/fx_table.json', ROOT), 'utf8'));
const fxKey = (name) => String(name).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
fxTable.forEach((f, i) => {
  if (fxKey(f.name) !== FX_IDS[i]) throw new Error(`fx table entry ${i} (${f.name}) does not match firmware enum ${FX_IDS[i]}`);
});

const isNum = (v) => typeof v === 'number' && Number.isFinite(v);
const KNOWN_TOP = new Set(['schema', 'version', 'name', 'inputGainDb', 'master', 'bpm', 'order', 'globalBypass', 'slots']);
const KNOWN_SLOT = new Set(['fx', 'bypass', 'wet', 'params']);

export function validate(p, file) {
  const errs = [];
  const err = (m) => errs.push(`${file}: ${m}`);
  if (!p || typeof p !== 'object' || Array.isArray(p)) { err('not an object'); return errs; }
  if (p.schema !== 'sp1fx.preset') err(`schema must be "sp1fx.preset"`);
  if (p.version !== 1) err('version must be 1');
  if (typeof p.name !== 'string' || !p.name.trim() || p.name.length > 40 || !/^[\x20-\x7e]+$/.test(p.name)) err('name must be 1..40 printable ASCII chars');
  if (!isNum(p.inputGainDb) || p.inputGainDb < -12 || p.inputGainDb > 12) err('inputGainDb must be -12..12');
  if (!isNum(p.master) || p.master < 0 || p.master > 1) err('master must be 0..1');
  if (!isNum(p.bpm) || p.bpm < 30 || p.bpm > 300) err('bpm must be 30..300');
  if (typeof p.globalBypass !== 'boolean') err('globalBypass must be boolean');
  if (!Array.isArray(p.order) || p.order.length !== 4 || ![0, 1, 2, 3].every((v) => p.order.includes(v)) || !p.order.every(Number.isInteger))
    err('order must be a permutation of 0..3');
  for (const k of Object.keys(p)) if (!KNOWN_TOP.has(k)) err(`unknown key "${k}" (factory files must be exact)`);
  if (!Array.isArray(p.slots) || p.slots.length !== 4) { err('slots must have exactly 4 entries'); return errs; }
  p.slots.forEach((s, i) => {
    const e = (m) => err(`slot ${i}: ${m}`);
    if (!s || typeof s !== 'object') { e('not an object'); return; }
    for (const k of Object.keys(s)) if (!KNOWN_SLOT.has(k)) e(`unknown key "${k}"`);
    const id = FX_IDS.indexOf(s.fx);
    if (id < 0) { e(`unknown fx "${s.fx}"`); return; }
    if (typeof s.bypass !== 'boolean') e('bypass must be boolean');
    if (!isNum(s.wet) || s.wet < 0 || s.wet > 1) e('wet must be 0..1');
    const np = fxTable[id].params.length;
    if (!Array.isArray(s.params) || s.params.length !== np) e(`params must have ${np} entries for ${s.fx}`);
    else s.params.forEach((v, j) => { if (!isNum(v) || v < 0 || v > 1) e(`param ${j} must be 0..1`); });
  });
  return errs;
}

// Real value of a normalised param, per docs/PROTOCOL.md (for the comment in the header).
function realValue(p, n) {
  if (p.scale === 'log') return p.min * Math.pow(p.max / p.min, n);
  if (p.scale === 'step') return Math.min(p.max, p.min + Math.floor(n * (p.max - p.min + 1)));
  return p.min + n * (p.max - p.min);
}

const f = (v) => { let s = String(v); if (!/[.e]/.test(s)) s += '.0'; return s + 'f'; };
const fmt = (v) => (Math.abs(v) >= 100 ? v.toFixed(0) : Number(v.toPrecision(3)).toString());

const presets = [];
let errors = [];
for (const file of FILES) {
  let p;
  try { p = JSON.parse(readFileSync(new URL('presets/' + file, ROOT), 'utf8')); }
  catch (e) { errors.push(`${file}: ${e.message}`); continue; }
  errors = errors.concat(validate(p, file));
  presets.push(p);
}
const names = presets.map((p) => p.name);
if (new Set(names).size !== names.length) errors.push('duplicate preset names');
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
if (process.argv.includes('--check')) { console.log(`${presets.length} presets valid`); process.exit(0); }

const o = [];
o.push('/* GENERATED by presets/gen_presets_h.mjs from the presets/ JSON files -- do not edit.');
o.push(' * Factory presets in the firmware\'s own config form, so the device can restore them');
o.push(' * without the companion. Params are normalised 0..1 (docs/PROTOCOL.md, preset schema v1). */');
o.push('#ifndef SP1FX_FACTORY_PRESETS_H');
o.push('#define SP1FX_FACTORY_PRESETS_H');
o.push('');
o.push('#include "../storage/config_store.h"');
o.push('');
o.push('typedef struct {');
o.push('\tconst char *name;');
o.push('\tuint8_t fx_id[ENGINE_SLOTS];');
o.push('\tuint8_t bypass[ENGINE_SLOTS];');
o.push('\tfloat wet[ENGINE_SLOTS];');
o.push('\tfloat params[ENGINE_SLOTS][FX_MAX_PARAMS]; /* for the slot\'s active effect */');
o.push('\tuint8_t order[ENGINE_SLOTS];');
o.push('\tuint8_t global_bypass;');
o.push('\tfloat in_gain_db, master, bpm;');
o.push('} factory_preset_t;');
o.push('');
o.push(`#define FACTORY_PRESET_COUNT ${presets.length}`);
o.push('');
o.push('static const factory_preset_t factory_presets[FACTORY_PRESET_COUNT] = {');
for (const p of presets) {
  const ids = p.slots.map((s) => FX_IDS.indexOf(s.fx));
  o.push(`\t{ /* ${p.name} */`);
  p.slots.forEach((s, i) => {
    const d = fxTable[ids[i]];
    const desc = d.params.map((q, j) => `${q.name} ${fmt(realValue(q, s.params[j]))}${q.unit ? ' ' + q.unit : ''}`).join(', ');
    o.push(`\t\t/* slot ${i}: ${d.name}${s.bypass ? ' (bypassed)' : ''}, wet ${s.wet}: ${desc} */`);
  });
  o.push(`\t\t${JSON.stringify(p.name)},`);
  o.push(`\t\t{ ${ids.join(', ')} },`);
  o.push(`\t\t{ ${p.slots.map((s) => (s.bypass ? 1 : 0)).join(', ')} },`);
  o.push(`\t\t{ ${p.slots.map((s) => f(s.wet)).join(', ')} },`);
  o.push(`\t\t{ ${p.slots.map((s) => `{ ${[0, 1, 2, 3].map((j) => f(s.params[j] ?? 0)).join(', ')} }`).join(', ')} },`);
  o.push(`\t\t{ ${p.order.join(', ')} },`);
  o.push(`\t\t${p.globalBypass ? 1 : 0},`);
  o.push(`\t\t${f(p.inputGainDb)}, ${f(p.master)}, ${f(p.bpm)}`);
  o.push('\t},');
}
o.push('};');
o.push('');
o.push('/* Fill a complete store record: defaults for everything the preset does not mention (remembered');
o.push(' * params of inactive effects), then the preset. Apply with engine_apply_config(e, &d->cfg). */');
o.push('static inline void factory_preset_fill(const factory_preset_t *p, store_data_t *d)');
o.push('{');
o.push('\tstore_data_default(d);');
o.push('\tfor (int s = 0; s < ENGINE_SLOTS; s++) {');
o.push('\t\td->cfg.fx_id[s] = p->fx_id[s];');
o.push('\t\td->cfg.bypass[s] = p->bypass[s];');
o.push('\t\td->cfg.wet[s] = p->wet[s];');
o.push('\t\td->cfg.order[s] = p->order[s];');
o.push('\t\tconst fx_desc *fd = fx_get(p->fx_id[s]);');
o.push('\t\tfor (int i = 0; fd && i < fd->nparams; i++) d->cfg.params[s][p->fx_id[s]][i] = p->params[s][i];');
o.push('\t}');
o.push('\td->cfg.global_bypass = p->global_bypass;');
o.push('\td->cfg.in_gain_db = p->in_gain_db;');
o.push('\td->cfg.master = p->master;');
o.push('\td->bpm = p->bpm;');
o.push('}');
o.push('');
o.push('#endif');
writeFileSync(new URL('firmware/app/factory_presets.h', ROOT), o.join('\n') + '\n');
console.log(`wrote firmware/app/factory_presets.h (${presets.length} presets)`);
