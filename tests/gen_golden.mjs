// ------------------------------------------------------------------ FX_DESC x 11 (from the companion's fx table)
out.push('typedef struct { const char *name, *unit; float min, max, def; uint8_t scale; const char *labels; } golden_param_t;');
out.push('typedef struct { uint8_t id; const char *name; uint8_t nparams; uint16_t cpu; uint32_t mem, tail; uint8_t mix; golden_param_t p[4]; const uint8_t *frame; uint16_t len; } golden_fx_t;');
const SC = { lin: 0, log: 1, step: 2 };
const fxRows = [];
for (const fx of fxTable) {
  const msg = { type: T.FX_DESC, id: fx.id, name: fx.name, cpuCycles: fx.cpuCycles, memBytes: fx.memBytes, tailMs: fx.tailMs,
    mixMode: fx.mixMode, params: fx.params.map((p) => ({ ...p, labels: p.labels || '' })) };
  const fr = buildFrame(msg, 0x40 + fx.id);
  const m = jsDecode(fr).msg;
  out.push(`static const uint8_t g_fx_${fx.id}[] = { ${hex(fr)} };`);
  const ps = m.params.map((p) => `{ ${cstr(p.name)}, ${cstr(p.unit)}, ${cfloat(p.min)}, ${cfloat(p.max)}, ${cfloat(p.def)}, ${SC[p.scale]}, ${cstr(p.labels)} }`);
  fxRows.push(`\t{ ${m.id}, ${cstr(m.name)}, ${m.params.length}, ${m.cpuCycles}, ${m.memBytes}u, ${m.tailMs}u, ${m.mixMode === 'send' ? 1 : 0}, { ${ps.join(', ') || '{0}'} }, g_fx_${fx.id}, ${fr.length} },`);
}
out.push('static const golden_fx_t golden_fx[] = {');
out.push(...fxRows);
out.push('};');
out.push(`#define GOLDEN_NFX ${fxTable.length}`);
out.push('#define G_FX_SEQ(id) (0x40 + (id))');
out.push('');

// ------------------------------------------------------------------ small device->host messages
