// ------------------------------------------------------------------ STATE (factory default)
// Default params use the firmware/spec unmap (step: (v-min+0.5)/(max-min+1)); see the report
// for the companion's different step mapping.
function unmapSpec(p, v) {
  if (p.scale === 'log') return Math.log(v / p.min) / Math.log(p.max / p.min);
  if (p.scale === 'step') return (v - p.min + 0.5) / (p.max - p.min + 1);
  return (v - p.min) / (p.max - p.min);
}
const nfx = fxTable.length;
const params = [];
for (let s = 0; s < 4; s++) {
  const per = [];
  for (let f = 0; f < nfx; f++) {
    const ps = fxTable[f].params;
    per.push([0, 1, 2, 3].map((i) => (i < ps.length ? unmapSpec(ps[i], ps[i].def) : 0)));
  }
  params.push(per);
}
const state = { type: T.STATE, fxId: [1, 2, 3, 4], bypass: [true, true, true, true], order: [0, 1, 2, 3], globalBypass: false,
  fxCount: nfx, inGainCdB: 0, master: 0.75, bpm10: 1200, wet: [0.5, 0.5, 0.5, 0.5], params, uiMode: 0, editSlot: 0 };
{
  const fr = buildFrame(state, 4);
  const m = jsDecode(fr).msg;
  out.push(`static const uint8_t g_state_default[] = { ${hex(fr)} };`);
  out.push('/* JS-decoded STATE fields (u16n as integer codes) */');
  out.push(`static const uint8_t g_state_fx[4] = { ${m.fxId.join(', ')} };`);
  out.push(`static const uint8_t g_state_bypass[4] = { ${m.bypass.map((b) => (b ? 1 : 0)).join(', ')} };`);
  out.push(`static const uint8_t g_state_order[4] = { ${m.order.join(', ')} };`);
  out.push(`#define G_STATE_GLOBAL ${m.globalBypass ? 1 : 0}`);
  out.push(`#define G_STATE_FXCOUNT ${m.fxCount}`);
  out.push(`#define G_STATE_INGAIN ${m.inGainCdB}`);
  out.push(`#define G_STATE_MASTER ${q(m.master)}u`);
  out.push(`#define G_STATE_BPM10 ${m.bpm10}u`);
  out.push(`static const uint16_t g_state_wet[4] = { ${m.wet.map(q).join(', ')} };`);
  out.push(`static const uint16_t g_state_params[4][${nfx}][4] = {`);
  for (const per of m.params) out.push('\t{ ' + per.map((r) => `{ ${r.map(q).join(', ')} }`).join(', ') + ' },');
  out.push('};');
  out.push(`#define G_STATE_UIMODE ${m.uiMode}`);
  out.push(`#define G_STATE_EDITSLOT ${m.editSlot}`);
  out.push(`#define G_STATE_PAYLOAD_LEN ${fr.length > 0 ? 29 + 4 * nfx * 4 * 2 + 2 + 1 : 0}`); // + out_mode (rc4)
}
out.push('');
out.push('#endif');
process.stdout.write(out.join('\n') + '\n');
